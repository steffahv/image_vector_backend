"""Base class, schemas and shared columns for every SQLAlchemy model.

What goes here:
- `Base`, the class every table inherits from.
- `DbSchema`, the PostgreSQL schemas. Every table lives in one of them, never in `public`.
- Mixins with the columns most tables share: `UUIDPrimaryKey`, `Timestamps` and `CreatedAt`.
- `text_enum()`, the column type for statuses and other closed lists of values.
- `sha256_check()`, the CHECK for columns that store a SHA-256 digest.

What does not go here: the engine or sessions (core/db.py) or concrete tables
(each module's models/).
This file must not read settings, so models can be imported without a database.
"""

import uuid
from datetime import datetime
from enum import StrEnum

from sqlalchemy import DateTime, Enum, LargeBinary, MetaData, Text, Uuid, func, text
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Fixed names for keys, indexes and constraints so Alembic generates stable migrations.
# `column_0_N_name` joins every column, so composite constraints get unique names.
NAMING_CONVENTION = {
    "pk": "pk_%(table_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
}


class DbSchema(StrEnum):
    """PostgreSQL schemas. Created by migration 0002."""

    AUTH = "auth"
    PLATFORM = "platform"
    STORAGE = "storage"
    BILLING = "billing"
    AGENT = "agent"
    OPERATIONS = "operations"


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)

    # Every str is text, bytes bytea, datetime timestamptz and UUID a native uuid,
    # without repeating it per column.
    type_annotation_map = {
        str: Text(),
        bytes: LargeBinary(),
        datetime: DateTime(timezone=True),
        uuid.UUID: Uuid(native_uuid=True),
    }


class UUIDPrimaryKey:
    """`id uuid` primary key generated by PostgreSQL with UUIDv7.

    Generated in the database so rows inserted by the agent service get one too.
    UUIDv7 starts with the creation time, so new rows go to the end of the index instead of
    a random place, which keeps large indexes compact. `uuidv7()` is native in PostgreSQL 18
    and created by migration 0004 for older versions.
    """

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, server_default=text("uuidv7()"))


class CreatedAt:
    """`created_at`, filled by PostgreSQL. For rows that never change after insert."""

    created_at: Mapped[datetime] = mapped_column(server_default=func.now())


class Timestamps:
    """`created_at` and `updated_at`, filled by PostgreSQL.

    `updated_at` is refreshed on ORM updates. Raw SQL updates must set it themselves.
    """

    created_at: Mapped[datetime] = mapped_column(server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(server_default=func.now(), onupdate=func.now())


SHA256_BYTES = 32


def sha256_check(column: str) -> str:
    """CHECK expression: the bytea column holds exactly one SHA-256 digest."""
    return f"octet_length({column}) = {SHA256_BYTES}"


def text_enum(enum_class: type[StrEnum], name: str) -> Enum:
    """Column type for a closed list of values: stored as text with a CHECK constraint.

    Not a native PostgreSQL enum, because changing one in a migration is awkward.
    `name` names the CHECK constraint: use the column name, e.g. "agent_mode".
    The naming convention turns it into `ck_<table>_<name>`.
    """
    return Enum(
        enum_class,
        name=name,
        native_enum=False,
        create_constraint=True,
        length=None,
        values_callable=lambda members: [member.value for member in members],
    )
